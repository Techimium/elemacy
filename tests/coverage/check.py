#!/usr/bin/env python3
"""Validate inventory declarations and render the current coverage roadmap."""

import argparse
import json
from pathlib import Path

from catalog import FREE, PRO, declarations, runners


def validate(value, schema, at='$'):
    types = {'object': dict, 'array': list, 'string': str}
    if 'type' in schema and not isinstance(value, types[schema['type']]):
        raise ValueError(at + ': wrong type')
    if 'const' in schema and value != schema['const']:
        raise ValueError(at + ': unsupported schema version')
    if 'enum' in schema and value not in schema['enum']:
        raise ValueError(at + ': unsupported value')
    if isinstance(value, str) and len(value) < schema.get('minLength', 0):
        raise ValueError(at + ': empty value')
    if isinstance(value, list):
        if len(value) < schema.get('minItems', 0):
            raise ValueError(at + ': empty list')
        for index, item in enumerate(value):
            validate(item, schema.get('items', {}), f'{at}[{index}]')
    if isinstance(value, dict):
        for key in schema.get('required', []):
            if key not in value:
                raise ValueError(at + ': missing ' + key)
        for key, item in value.items():
            if key in schema.get('properties', {}):
                validate(item, schema['properties'][key], at + '.' + key)


def check(root):
    inventory = json.loads((root / 'tests/coverage/inventory.json').read_text())
    schema = json.loads((FREE / 'tests/coverage/inventory.schema.json').read_text())
    validate(inventory, schema)
    if inventory['owner'] != root.name:
        raise ValueError('Wrong inventory owner: ' + root.name)
    entries = inventory['features'] + inventory['runners']
    ids = [entry['id'] for entry in entries] + [f['journey']['id'] for f in inventory['features']]
    if len(ids) != len(set(ids)):
        raise ValueError('Duplicate inventory/journey IDs: ' + root.name)
    actual = {f['id']: f for f in declarations(root)}
    declared = {f['id']: f for f in inventory['features']}
    if actual.keys() != declared.keys():
        raise ValueError(f'{root.name}: uncovered={sorted(actual.keys() - declared.keys())}; stale={sorted(declared.keys() - actual.keys())}')
    for id, feature in actual.items():
        if any(declared[id][key] != value for key, value in feature.items()):
            raise ValueError('Declaration changed: ' + id)
    known = {entry['id'] for entry in inventory['runners']}
    if inventory['runners'] != runners(root):
        raise ValueError('Existing test runner list changed: ' + root.name)
    for feature in inventory['features']:
        for reference in feature['coverage']:
            if reference not in known:
                raise ValueError('Unresolved test reference: ' + reference)
        journey = feature['journey']
        if journey['status'] != 'implemented' and (not journey['reason'] or not journey['follow_up']):
            raise ValueError('Missing gap explanation: ' + feature['id'])
    for runner in inventory['runners']:
        if not (root / runner['path']).is_file():
            raise ValueError('Missing runner: ' + runner['path'])
    return inventory


def markdown(inventory):
    lines = ['# ' + inventory['owner'] + ' browser coverage roadmap', '',
             'Generated by `python3 tests/coverage/check.py --write-roadmap`. Do not edit this file directly.', '',
             'Inventory validation is not a release pass. Pending journeys have not been automated or verified.', '',
             'Taxonomy identifiers with `{taxonomy}` represent a family; native tests must exercise registered public taxonomies.', '',
             '| Feature | Implementation | Prerequisites | Journey status |',
             '| --- | --- | --- | --- |']
    for entry in inventory['features']:
        lines.append(f"| `{entry['kind']}:{entry['identifier']}` | {entry['implementation']} | {', '.join(entry['prerequisites']) or 'Elementor Free'} | {entry['journey']['status']} |")
    lines.extend(['', '## Existing checks', '',
                  'Runner presence does not imply a successful run or complete feature coverage.', '',
                  '| ID | Layer | File |', '| --- | --- | --- |'])
    for entry in inventory['runners']:
        lines.append(f"| `{entry['id']}` | {entry['layer']} | `{entry['path']}` |")
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--owner', choices=['elemacy', 'elemacy-pro', 'both'], default='both')
    parser.add_argument('--write-roadmap', action='store_true')
    parser.add_argument('--require-journeys', action='store_true')
    args = parser.parse_args()
    roots = [FREE, PRO] if args.owner == 'both' else [FREE if args.owner == 'elemacy' else PRO]
    missing = []
    for root in roots:
        inventory = check(root)
        output = root / 'tests/coverage/ROADMAP.md'
        document = markdown(inventory)
        if args.write_roadmap:
            output.write_text(document)
        elif not output.exists() or output.read_text() != document:
            raise ValueError('Generated roadmap is stale: ' + str(output))
        pending = [f['journey']['id'] for f in inventory['features'] if f['journey']['status'] != 'implemented']
        missing += pending
        print(f"{root.name}: {len(inventory['features'])} declarations, {len(inventory['runners'])} existing checks, {len(pending)} pending journeys")
    if args.require_journeys and missing:
        raise ValueError(f'Release coverage incomplete: {len(missing)} pending journeys')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, KeyError) as error:
        raise SystemExit(str(error))
